#!/usr/bin/env python3
"""Build/check offline browser input contract from validated synthetic suite fixtures."""
from pathlib import Path
import argparse
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))
from app.synthetic_integrated_intelligence import (  # noqa: E402
    FIXTURE, parse_suite_fixture, build_integrated_suite,
)
from app.synthetic_growth_value_intelligence import SCENARIOS, build_committed_value_report  # noqa: E402

OUTPUT = ROOT / "apps/site/intelligence-lab/data.js"


def create_contract():
    domain = parse_suite_fixture(FIXTURE.read_bytes())
    financial = json.loads(SCENARIOS.read_text(encoding="utf-8"))
    report = build_committed_value_report()
    assert report["classification"] == "SYNTHETIC_SOURCE_ONLY"
    fw = {x["workspace"]: x for x in financial["workspaces"]}
    result = {"schema_version": 1, "classification": "SYNTHETIC_SOURCE_ONLY",
              "units": "DEMO_CREDITS_NOT_USD", "workspaces": {}}
    for d in domain["workspaces"]:
        name = d["workspace"]
        validated = build_integrated_suite(name)
        assert validated["safety"]["provider_calls"] == 0
        assert validated["safety"]["production_ready"] is False
        item = {key: value for key, value in d.items() if key != "workspace"}
        item["baseline"] = fw[name]["baseline"]
        item["current"] = fw[name]["current"]
        result["workspaces"][name] = item
    return result


def render():
    data = json.dumps(create_contract(), sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return ("/* Generated by scripts/build_intelligence_lab_contract.py. "
            "Only simulated numbers, not real business records. */\n"
            "window.MetaAutomateSuiteData = Object.freeze(" + data + ");\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("Unified Intelligence Lab browser contract stale", file=sys.stderr)
            return 1
        print("Unified Intelligence Lab browser contract matches source")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print("Wrote synthetic browser contract")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
